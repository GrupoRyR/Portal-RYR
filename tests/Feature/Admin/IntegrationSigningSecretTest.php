<?php

namespace Tests\Feature\Admin;

use App\Auth\RecentMicrosoftLogin;
use App\Livewire\Admin\IntegrationManager;
use App\Models\App;
use App\Models\Company;
use App\Models\Integration;
use App\Models\User;
use Carbon\CarbonImmutable;
use Database\Seeders\RoleSeeder;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\DB;
use Livewire\Features\SupportTesting\Testable;
use Livewire\Livewire;
use Spatie\Activitylog\Models\Activity;
use Tests\TestCase;

/**
 * «Secreto de firma» of Administración › Integraciones
 * (docs/contrato-tareas-aprobaciones.md §2.2, §6.2): the secret the portal
 * signs «Completar» with. Generated by the portal, stored encrypted, shown
 * once when generated or rotated, and only behind a recent Microsoft
 * sign-in, like a token.
 */
class IntegrationSigningSecretTest extends TestCase
{
    use RefreshDatabase;

    private Company $segurex;

    private User $admin;

    private Integration $tasks;

    protected function setUp(): void
    {
        parent::setUp();

        $this->seed(RoleSeeder::class);
        $this->travelTo(CarbonImmutable::parse('2026-11-04 09:00', 'America/Bogota'));

        $this->segurex = Company::factory()->create(['name' => 'Segurex Latam', 'slug' => 'segurex']);
        $this->admin = User::factory()->microsoft($this->segurex)->create(['name' => 'Jhon Castro']);
        $this->admin->assignRole('super_admin');

        $app = App::factory()->create(['slug' => 'tareas', 'name' => 'Tareas y aprobaciones', 'url' => 'https://tareas.segurex.com.co']);
        $this->tasks = Integration::factory()->create([
            'name' => 'App de tareas',
            'abilities' => [Integration::WORK_WRITE],
            'app_id' => $app->id,
            'app_base_url' => 'https://tareas.segurex.com.co',
        ]);
        $this->tasks->issueToken();
    }

    private function manager(bool $fresh = true): Testable
    {
        if ($fresh) {
            session()->put(RecentMicrosoftLogin::SESSION_KEY, ['user_id' => $this->admin->id, 'at' => now()->getTimestamp()]);
        } else {
            session()->forget(RecentMicrosoftLogin::SESSION_KEY);
        }

        return Livewire::actingAs($this->admin)->test(IntegrationManager::class)->call('select', $this->tasks->id);
    }

    private function entries(string $event)
    {
        return Activity::query()->where('log_name', Integration::AUDIT_LOG)->where('event', $event)->get();
    }

    public function test_a_work_write_system_without_a_secret_says_completar_does_not_work_yet(): void
    {
        $this->manager()
            ->assertSee('Secreto de firma')
            ->assertSee('Sin secreto: «Completar» no funciona hasta generarlo.')
            ->assertSee('Generar secreto');
    }

    public function test_generating_shows_the_secret_once_and_stores_it_encrypted(): void
    {
        $component = $this->manager()
            ->call('generateSigningSecret')
            ->assertSee('Secreto de firma creado')
            ->assertSee('Cópialo ahora.');

        $plain = $component->get('plainSecret');
        $this->assertMatchesRegularExpression('/\Aryrsig_[A-Za-z0-9_-]{43}\z/', $plain);

        $this->tasks->refresh();
        $this->assertSame($plain, $this->tasks->signing_secret);
        $this->assertSame(substr($plain, -4), $this->tasks->signing_secret_hint);

        $stored = (string) DB::table('integrations')->where('id', $this->tasks->id)->value('signing_secret');
        $this->assertNotSame('', $stored);
        $this->assertStringNotContainsString($plain, $stored);
        $this->assertStringNotContainsString(substr($plain, 7), $stored);
        $this->assertArrayNotHasKey('signing_secret', $this->tasks->toArray());

        $entry = $this->entries('integration.signing_secret_created')->sole();
        $this->assertTrue($entry->causer->is($this->admin));
        $this->assertStringNotContainsString($plain, json_encode($entry->toArray()));

        // Once dismissed it is gone; the detail shows only its last characters.
        $component->call('dismissSecret')
            ->assertSet('plainSecret', null)
            ->assertDontSee($plain)
            ->assertSee('ryrsig_…'.substr($plain, -4))
            ->assertSee('Rotar secreto');
    }

    public function test_rotating_replaces_the_secret_at_once(): void
    {
        $old = $this->tasks->issueSigningSecret();

        $component = $this->manager()
            ->call('generateSigningSecret')
            ->assertSee('Secreto de firma nuevo')
            ->assertSee('El anterior ya no firma.');

        $plain = $component->get('plainSecret');
        $this->assertNotSame($old, $plain);
        $this->assertSame($plain, $this->tasks->fresh()->signing_secret);
        $this->assertCount(1, $this->entries('integration.signing_secret_rotated'));
        $this->assertCount(0, $this->entries('integration.signing_secret_created'));
    }

    public function test_it_needs_a_recent_microsoft_sign_in(): void
    {
        $this->manager(fresh: false)
            ->call('generateSigningSecret')
            ->assertRedirect(route('auth.microsoft.confirm', ['return' => '/admin/integraciones?sistema='.$this->tasks->id]))
            ->assertSet('plainSecret', null);

        $this->assertNull($this->tasks->fresh()->signing_secret);
        $this->assertCount(0, $this->entries('integration.signing_secret_created'));
    }

    public function test_emergency_accounts_cannot_generate_it(): void
    {
        $emergency = User::factory()->emergency()->create();
        $emergency->assignRole('super_admin');

        Livewire::actingAs($emergency)->test(IntegrationManager::class)
            ->call('select', $this->tasks->id)
            ->call('generateSigningSecret')
            ->assertForbidden();

        $this->assertNull($this->tasks->fresh()->signing_secret);
    }

    public function test_only_a_live_system_with_work_write_gets_one(): void
    {
        $monitor = Integration::factory()->create(['name' => 'Monitor', 'abilities' => [Integration::CATALOG_READ]]);

        Livewire::actingAs($this->admin)->test(IntegrationManager::class)
            ->call('select', $monitor->id)
            ->assertDontSee('Generar secreto')
            ->call('generateSigningSecret')
            ->assertSet('plainSecret', null);

        $this->assertNull($monitor->fresh()->signing_secret);
    }

    public function test_revoking_deletes_the_secret(): void
    {
        $this->tasks->issueSigningSecret();

        $this->manager()->call('revoke')->call('generateSigningSecret')->assertSet('plainSecret', null);

        $this->tasks->refresh();
        $this->assertNull($this->tasks->signing_secret);
        $this->assertNull($this->tasks->signing_secret_hint);
    }

    public function test_the_secret_changes_show_in_auditoria(): void
    {
        $this->manager()->call('generateSigningSecret')->call('dismissSecret')->call('generateSigningSecret');

        $this->actingAs($this->admin)->get(route('admin.audit.index'))
            ->assertSeeText('Generó el secreto de firma de App de tareas')
            ->assertSeeText('Rotó el secreto de firma de App de tareas');
    }

    public function test_an_admin_without_the_integrations_section_cannot_generate_it(): void
    {
        $component = $this->manager();

        $this->admin->removeRole('super_admin');
        $this->admin->assignRole('portal_admin');

        $component->call('generateSigningSecret')->assertForbidden();

        $this->assertNull($this->tasks->fresh()->signing_secret);
    }
}
